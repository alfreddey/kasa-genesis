// Generates src/lib/api-types.gen.ts from ../api/openapi.json (issue #27).
//   npm run generate:api   write the file
//   npm run check:api      fail if the committed file is out of date (used in CI)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const spec = new URL("../../api/openapi.json", import.meta.url);
const out = fileURLToPath(new URL("../src/lib/api-types.gen.ts", import.meta.url));

const banner = "/* Generated by `npm run generate:api` from api/openapi.json. Do not edit. */\n\n";
const generated = banner + astToString(await openapiTS(spec));

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== generated) {
    console.error("src/lib/api-types.gen.ts is out of date. Run: npm run generate:api");
    process.exit(1);
  }
  console.log("API types are up to date.");
} else {
  writeFileSync(out, generated);
  console.log("Wrote src/lib/api-types.gen.ts");
}
